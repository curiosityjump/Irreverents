// Writes the index.gen.ts registries: one per directory of self-registering
// files. Run first by build, check, gates, trace and dev.
//
// INTENT: the registries are generated and git-ignored, never hand-kept
// lists. Steps 2, 3 and 4 build in parallel and every push deploys; a
// hand-kept list of verbs or systems is the one file all of them would
// edit in the same hour (docs/plan/step-1.md, "Built for several leads at
// once"). Adding a verb, system, content kind or fact is adding one file
// that default-exports it.
import fs from 'node:fs';
import path from 'node:path';

export const root = path.resolve(import.meta.dirname, '../..');

/** Directories whose every .ts file default-exports one registered thing. */
export const REGISTRY_DIRS = ['src/content/kinds', 'src/sim/systems', 'src/sim/verbs', 'src/scenarios/facts'];

export function generateRegistries(): void {
  for (const dir of REGISTRY_DIRS) {
    const abs = path.join(root, dir);
    const files = fs
      .readdirSync(abs)
      .filter((f) => f.endsWith('.ts') && !f.endsWith('.gen.ts') && !f.endsWith('.d.ts'))
      .sort();
    const lines = [
      `// GENERATED by scripts/lib/registries.ts from the files in ${dir}/. Do not edit; not committed.`,
      ...files.map((f, i) => `import m${i} from './${f}';`),
      `export default [${files.map((_, i) => `m${i}`).join(', ')}];`,
      '',
    ];
    const out = path.join(abs, 'index.gen.ts');
    const text = lines.join('\n');
    // Only touch the file when it changed, so watchers do not loop.
    if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) fs.writeFileSync(out, text);
  }
}
